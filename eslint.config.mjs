import typescriptEslint from '@typescript-eslint/eslint-plugin';
import html from 'eslint-plugin-html';
import tsParser from '@typescript-eslint/parser';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import js from '@eslint/js';
import { FlatCompat } from '@eslint/eslintrc';
import elementsPlugin from './eslint/index.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const compat = new FlatCompat({
  baseDirectory: __dirname,
  recommendedConfig: js.configs.recommended,
  allConfig: js.configs.all,
});

// Flat config has no equivalent to extending a rule's existing options, so
// both `no-restricted-imports` blocks below spread this in rather than
// repeating it.
const customElementRestrictedImports = [
  {
    name: 'lit/decorators.js',
    importNames: ['customElement'],
    message:
      "Import customElement from '@src/utils/custom-element' instead, so a tag already claimed by another bundle of this package is skipped rather than throwing.",
  },
  {
    name: 'lit/decorators/custom-element.js',
    importNames: ['customElement'],
    message:
      "Import customElement from '@src/utils/custom-element' instead, so a tag already claimed by another bundle of this package is skipped rather than throwing.",
  },
];

// Published `@internetarchive/*` packages that elements now carries its own copy
// of under src/services. Importing the standalone package would pull in a second
// copy, so each one is restricted. `paths` catches the bare specifier and
// `patterns` catches deep imports like `<pkg>/dist/...`.
// When a package is migrated into src/services, add it to `migratedPackages`.
const migratedPackages = [
  { pkg: 'analytics-manager', dir: 'analytics-manager' },
  { pkg: 'fetch-handler', dir: 'fetch-handler' },
  { pkg: 'field-parsers', dir: 'field-parsers' },
  { pkg: 'iaux-item-metadata', dir: 'item-metadata' },
  { pkg: 'lazy-loader-service', dir: 'lazy-loader-service' },
  { pkg: 'metadata-service', dir: 'metadata-service' },
  { pkg: 'promised-singleton', dir: 'promised-singleton' },
  { pkg: 'recaptcha-manager', dir: 'recaptcha-manager' },
  { pkg: 'result-type', dir: 'result-type' },
  { pkg: 'search-service', dir: 'search-service' },
  { pkg: 'user-service', dir: 'user-service' },
];

const migratedPackageMessage = (dir) =>
  `Moved into elements. Import from '@src/services/${dir}' instead.`;

const migratedPackageRestrictedImports = migratedPackages.map(
  ({ pkg, dir }) => ({
    name: `@internetarchive/${pkg}`,
    message: migratedPackageMessage(dir),
  }),
);

const migratedPackageRestrictedPatterns = migratedPackages.map(
  ({ pkg, dir }) => ({
    group: [`@internetarchive/${pkg}/*`],
    message: migratedPackageMessage(dir),
  }),
);

export default [
  ...compat.extends('plugin:@typescript-eslint/recommended'),
  {
    plugins: {
      '@typescript-eslint': typescriptEslint,
      elements: elementsPlugin,
      html,
    },

    languageOptions: {
      parser: tsParser,
    },

    settings: {
      'import/resolver': {
        node: {
          extensions: ['.ts', '.tsx'],
          moduleDirectory: ['node_modules', 'src', 'demo'],
        },
      },
    },

    rules: {
      '@typescript-eslint/no-unsafe-function-type': 'warn',
      '@typescript-eslint/no-unused-vars': 'warn',
      '@typescript-eslint/no-explicit-any': 'warn',

      'elements/no-hand-built-download-url': 'error',

      'no-restricted-imports': [
        'error',
        {
          paths: [
            ...customElementRestrictedImports,
            ...migratedPackageRestrictedImports,
          ],
          patterns: [...migratedPackageRestrictedPatterns],
        },
      ],
    },
  },
  {
    ignores: [
      '**/*.js',
      '**/*.mjs',
      '**/*.d.ts',
      '.claude/',
      '.wireit/',
      // Generated by `pnpm run strings:build`. Its eslint-disable comments go
      // unused, so `eslint --fix` would strip them and leave the file out of
      // step with what the build writes.
      'src/locales/*.ts',
      '!src/locales/*.test.ts',
      // Generated by `pnpm run icons` from icons/*.svg.
      'src/icons/',
    ],
  },
  {
    files: ['**/*.test.ts'],
    rules: {
      '@typescript-eslint/no-unused-expressions': 'off',
      'elements/no-hand-built-download-url': 'off',
    },
  },
  {
    // The helper is the one place that spells out /download/.
    files: ['src/utils/download-url/download-url.ts'],
    rules: { 'elements/no-hand-built-download-url': 'off' },
  },
  {
    // Only the demo app calls configureLocalization (demo/demo-localization.ts).
    // @lit/localize throws if it's configured twice, so this package's own
    // source never does. Test files are exempt: they stand in for the app to
    // exercise a published locale module on its own.
    files: ['src/**/*.ts'],
    ignores: ['src/**/*.test.ts'],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          paths: [
            ...customElementRestrictedImports,
            ...migratedPackageRestrictedImports,
            {
              name: '@lit/localize',
              importNames: [
                'configureLocalization',
                'configureTransformLocalization',
              ],
              message:
                'Only the demo app (demo/demo-localization.ts) calls configureLocalization. @lit/localize throws if configured twice, so this package never does.',
            },
          ],
          patterns: [
            ...migratedPackageRestrictedPatterns,
            {
              // configureLocalization and configureTransformLocalization also
              // live at these deep import paths, which the `paths` entry
              // above (matched on the `@lit/localize` specifier alone)
              // doesn't catch.
              group: ['@lit/localize/init/*'],
              message:
                'Only the demo app (demo/demo-localization.ts) calls configureLocalization. @lit/localize throws if configured twice, so this package never does.',
            },
          ],
        },
      ],
    },
  },
];
